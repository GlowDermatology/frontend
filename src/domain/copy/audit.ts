/** Editable models written through the panel and the ops console (`<model>.created|updated|deleted`). */
type ModelKey =
  | "location"
  | "professional"
  | "service"
  | "professional_service"
  | "working_hours"
  | "blocked_period"
  | "working_hours_override";

type Verb = "created" | "updated" | "deleted";

/** `<model>.<verb>` labels from the model names and one phrase per verb. */
function modelActions(
  models: Record<ModelKey, string>,
  phrase: (model: string, verb: Verb, key: ModelKey) => string,
): Record<`${ModelKey}.${Verb}`, string> {
  const out = {} as Record<`${ModelKey}.${Verb}`, string>;
  for (const [model, label] of Object.entries(models) as Array<[ModelKey, string]>) {
    for (const verb of ["created", "updated", "deleted"] as const) {
      out[`${model}.${verb}`] = phrase(label, verb, model);
    }
  }
  return out;
}

